/**
 * Correlation ID middleware for Node.js HTTP servers (http.IncomingMessage /
 * http.ServerResponse). ESM, zero third-party dependencies.
 */

/**
 * Generate an RFC 4122 v4 UUID using the Web Crypto API, which is available
 * as a global in Node 18+ and in every modern browser. Using crypto.randomUUID
 * rather than a hand-rolled implementation keeps the library dependency-free
 * while still producing spec-compliant, cryptographically random identifiers.
 *
 * @returns {string} A lowercase v4 UUID, e.g. "1a2b3c4d-5e6f-4789-abcd-ef0123456789".
 */
export function uuid() {
  return crypto.randomUUID();
}

/**
 * Validate that a string is a plausible correlation identifier.
 *
 * We intentionally accept ANY RFC 4122 UUID variant (v1 through v5 and the
 * nil UUID) rather than only v4. A correlation ID propagated from an upstream
 * service may have been generated by a library that produces v1 (time-based)
 * or v5 (name-based) UUIDs; rejecting those would break propagation for no
 * real security gain, since the value is already trusted enough to echo back.
 *
 * We reject empty strings, strings with the wrong length, and strings whose
 * version or variant nibbles are out of range, but we do NOT enforce
 * lowercase — case-insensitive matching is standard for UUIDs (RFC 4122 §3).
 *
 * @param {unknown} value
 * @returns {boolean}
 */
export function isUuid(value) {
  if (typeof value !== 'string') {
    return false;
  }
  // 36 chars: 8-4-4-4-12 with hyphens at positions 8, 13, 18, 23.
  if (value.length !== 36) {
    return false;
  }
  if (
    value[8] !== '-' ||
    value[13] !== '-' ||
    value[18] !== '-' ||
    value[23] !== '-'
  ) {
    return false;
  }
  // All remaining 32 characters must be hex digits.
  for (let i = 0; i < 36; i++) {
    if (i === 8 || i === 13 || i === 18 || i === 23) {
      continue;
    }
    const code = value.charCodeAt(i);
    const isDigit = code >= 48 && code <= 57; // 0-9
    const isLowerHex = code >= 97 && code <= 102; // a-f
    const isUpperHex = code >= 65 && code <= 70; // A-F
    if (!isDigit && !isLowerHex && !isUpperHex) {
      return false;
    }
  }
  // Version nibble (position 14) must be 1-5 or 0 (nil UUID).
  const versionChar = value[14].toLowerCase();
  if (!'012345'.includes(versionChar)) {
    return false;
  }
  // Variant nibble (position 19): high bits must be 10xx, i.e. 8, 9, a, or b.
  const variantChar = value[19].toLowerCase();
  if (!'89ab'.includes(variantChar)) {
    return false;
  }
  return true;
}

/**
 * Create a correlation ID middleware.
 *
 * The middleware reads a correlation ID from the incoming request using the
 * configured header name. If the header is present and holds a syntactically
 * valid UUID, that value is reused. If the header is absent or holds garbage,
 * a fresh UUID is generated. The resolved ID is then:
 *
 *   - attached to the request via a non-enumerable property named after
 *     `propertyName`, so it does not leak when the request object is logged
 *     or serialized;
 *   - written onto the outgoing response as a header so downstream callers
 *     and log aggregators can correlate the reply with the request.
 *
 * The handler always calls `next()`, so it can be used in a chain.
 *
 * @param {object} [options]
 * @param {string} [options.headerName='x-correlation-id'] - Name of the request/response header.
 * @param {string} [options.propertyName='correlationId'] - Name of the property attached to the request.
 * @param {() => string} [options.generate=uuid] - Factory used to create a new ID when none is supplied.
 * @returns {(req: import('http').IncomingMessage, res: import('http').ServerResponse, next: () => void) => void}
 */
export function createCorrelationIdMiddleware(options = {}) {
  const {
    headerName = 'x-correlation-id',
    propertyName = 'correlationId',
    generate = uuid,
  } = options;

  if (typeof headerName !== 'string' || headerName.length === 0) {
    throw new TypeError('headerName must be a non-empty string');
  }
  if (typeof propertyName !== 'string' || propertyName.length === 0) {
    throw new TypeError('propertyName must be a non-empty string');
  }
  if (typeof generate !== 'function') {
    throw new TypeError('generate must be a function');
  }

  /**
   * Header names in Node.js are lowercased on the incoming message, so we
   * compare against a lowercased copy to avoid missing a header the caller
   * specified in mixed case.
   */
  const normalizedHeader = headerName.toLowerCase();

  return function correlationIdMiddleware(req, res, next) {
    const incoming = req.headers ? req.headers[normalizedHeader] : undefined;
    const value = typeof incoming === 'string' ? incoming : undefined;
    const id = isUuid(value) ? value : generate();

    // Non-enumerable so console.log(req) and JSON.stringify(req) don't
    // accidentally expose an internal correlation field.
    Object.defineProperty(req, propertyName, {
      value: id,
      writable: true,
      enumerable: false,
      configurable: true,
    });

    res.setHeader(headerName, id);
    next();
  };
}
